export function dependencyLedger(catalog){
 const ids=catalog.map(x=>x.id),known=new Set(ids);
 const edges=catalog.flatMap(d=>(d.id.startsWith('EYE-')?d.upstream_rank_item_ids:plannedRankDependencies[d.id]??[]).map(a=>[a,d.id]));
 if(ids.length!==115||known.size!==115||edges.some(([a,b])=>!known.has(a)||!known.has(b)||a===b))throw Error('DEPENDENCY_INVALID');
 const pending=new Set(ids),order=[];
 while(pending.size){const next=[...pending].filter(id=>edges.filter(e=>e[1]===id).every(e=>!pending.has(e[0]))).sort();if(!next.length)throw Error('DEPENDENCY_CYCLE');for(const n of next){pending.delete(n);order.push(n);}}
 return {edges,order,items:catalog.map(d=>({id:d.id,name:d.name,planned_inputs:edges.filter(e=>e[1]===d.id).map(e=>e[0]),planned_consumers:edges.filter(e=>e[0]===d.id).map(e=>e[1]),source_ids:d.source_ids,planned_order:order.indexOf(d.id)+1,extracted_from_execution:false})),full_runtime_dependency_extraction:false};
}
export function affectedItems(ledger,changed){
 const out=new Set(changed);let n=-1;while(n!==out.size){n=out.size;for(const [a,b] of ledger.edges)if(out.has(a))out.add(b);}return ledger.order.filter(x=>out.has(x));
}
